 "html":"<p>Denominatio. Das aristotelische παρώνυμον (wortverwandt) <sup class=\"fn\" data-fn=\"0-1\">1</sup> wurde von VICTORINUS durch ‹denominativum› übersetzt und bezieht sich zunächst auf die Nomina, die sich durch einen Wechsel der Endung unterscheiden, wie etwa der grammaticus nach der grammatica benannt wird. <span class=\"col\" data-col=\"113\"></span> Diese Unterscheidung verband sich mit derjenigen in absolute und konnotative Termini, insofern man die denominativen Termini als Sonderfall der konnotativen und relativen ansehen kann. So bezeichnen sie sowohl die Form wie auch das Subjekt dieser Form, d.h. sie haben ebenso formale wie materiale Bedeutung. Darüber hinaus unterschied man die Funktion einer D. <i>essentialis</i>, die beispielsweise ‹rationalis› zukommt, von der einer D. <i>accidentalis</i> etwa bei ‹album› <sup class=\"fn\" data-fn=\"0-2\">2</sup>.</p>\n<p>Eine andere Bedeutung der D. zeigt sich an, wenn DURANDUS de S. PORCIANO sagt, daß «ens rationis» eine D. <i>extrinseca</i> sei, abgeleitet aus der Tätigkeit der Vernunft. In diesem Sinn spricht man von einer D. <i>intrinseca</i>, die sich herleitet aus einer Form oder Qualität, die innerhalb des Subjekts ist, dabei kann sie innerlich sein durch Identität, so wenn ‹Mensch› aus der Form ‹Menschheit› hervorgeht, oder aber durch Inhärenz, wie z.B. die Mauer ‹weiß› genannt wird aufgrundder ihr eigenen Weiße. Von einer D. extrinseca spricht man, wenn sie zurückgeht auf eine dem benannten Objekt äußere und von ihm verschiedene Form, z.B. wenn man einen Tisch ‹gesehen› oder ‹bekannt› nennt und sich dabei einer Benennung bedient, die sich aus seinem Gesehen-bzw. Erkanntwerden herleitet. Die Seinsform dieser D. extrinseca war sehr umstritten: für viele war sie ein «ens mere rationis», für andere ein «ens reale», wieder andere sahen nur in der «forma denominans» etwas Reales, der auf Seiten des benannten Objekts nur ein Gedankending entsprach. Deshalb unterschieden letztere drei Elemente der D. extrinseca, nämlich die benennende Form, z.B. den Verstand, das Sehen; dann das benannte Ding, z.B. den Tisch; und schließlich die Benennung selbst, die erst daraus hervorgeht, daß beispielsweise der Tisch als ein Gesehenes oder Erkanntes bezeichnet wird <sup class=\"fn\" data-fn=\"0-3\">3</sup>.</p>\n<h3 id=\"notes\">Anmerkungen</h3><ol class=\"notes\">\n<li id=\"fn0-1\" value=\"1\">ARIST., De cat. 1 a 12.</li>\n<li id=\"fn0-2\" value=\"2\">PEDRO MARGALHO: Logices utriusque scholia (1520, Neu-A. 1965) 96. 106–108; PEDRO de FONSECA: Inst. Dialectic. (1564, Neu-A. 1964) 72–74.</li>\n<li id=\"fn0-3\" value=\"3\">C. PRANTL, Gesch. der Logik im Abendlande 3, 292; Collegium Ripense: Cursus philos. 1 (1716) 218ff.; JUAN de S. TOMAS: Ars logica (1631/32, Neu-A. 1930) 285–289.</li>\n</ol>",
