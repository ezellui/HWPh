 "html":"<p>Complexe significabile (Totalinhalt). In der logischen Terminologie des Mittelalters bezeichnet ‹complexum› das Urteil im Gegensatz zu den darin eingehenden termini (incomplexa) <sup class=\"fn\" data-fn=\"0-1\">1</sup>. Im Begriff Cs. klingt die ganze Diskussion über den Gegenstand wissenschaftlicher Erkenntnis mit an. Nach OCKHAM ist die oratio mentalis (innere Rede) der unmittelbare Gegenstand des Wissens, da nur diese notwendig und allgemein ist. Die oratio mentalis setzt sich aus Urteilen (complexa) zusammen, deren Totalinhalt in den Einzeldingen zu suchen ist, für die die termini stehen. Nach den <i>Realisten</i> hingegen ist der unmittelbare Gegenstand des Wissens die res significata und ihre Eigenschaften, denen das Urteil <i>entsprechen</i> muß. Um diesen Gegensatz zu überbrücken, schuf GREGOR VON RIMINI (1344) die Lehre vom C.s., nach der das unmittelbar Gewußte der im Urteil bezeichnete Totalinhalt (C.s.) ist, der sprachlich mit Hilfe des Akkusativs mit Infinitiv umschrieben wird. Das C.s. hat keine reale Existenz, sondern nur eine intentionale; es ist aber andererseits nicht mit den Begriffen der oratio mentalis identisch, sondern ist als ein formaler Eigenbereich aufzufassen. Diese Lehre wurde von den Nominalisten heftig angegriffen. Die dadurch entfachte Kontroverse wurde für die theologische Debatte des Spätmittelalters sehr wichtig, u.a. in ihrer Gleichsetzung des Glaubens<i>inhaltes</i> mit einem Glaubens<i>satz.</i></p>\n<h3 id=\"h1\">Literaturhinweise</h3>\n<p class=\"lit\">H. ELIE: Le c.s. (Paris 1937). – Zu vergleichen sind auch die neueren Artikel zum Thema von M. DAL PRA, Riv. crit. Storia Filos. 11 (1956) 15–40. 287–311; M. E. REINA, a.a.O. 15 (1960) 141–165; E. A. MOODY, Speculum 39 (1964) 53–74; T. K. SCOTT jr., a.a.O. 40 (1965) 654–673.</p>\n<h3 id=\"notes\">Anmerkungen</h3><ol class=\"notes\">\n<li id=\"fn0-1\" value=\"1\">Vgl. ARISTOTELES, Cat. 1 a 16ff.</li>\n</ol>",
