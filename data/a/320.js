 "html":"<p>Autofalsifikation bildet einen Sonderfall des reflexiven Satzes. <span class=\"col\" data-col=\"694\"></span> Eine «propositio se falsificans» ist eine Aussage, die auf sich selbst rückbezogen zur Folge hat, daß sie ihrer Bedeutung wegen falsch ist und dennoch, eben weil sie falsch ist, wegen der Korrespondenz mit dem Gesagten wahr ist. Wenn man hier die Wahrheits- und Falschheitskriterien, die bei den gewöhnlichen Aussagen gelten, anwendet, führen diese Sätze zu Widersprüchen oder Antinomien. Man unterscheidet verschiedene Fälle: die unmittelbare A. beispielsweise in der Aussage: «Diese Aussage ist falsch.» Die mittelbaren autofalsifizierenden Aussagen resultieren daraus, daß das Unmögliche dem Falschen und das Notwendige dem Wahren gleichgesetzt wird, so etwa in dieser sich selbst unmöglich machenden Aussage (autoimpossibilitans): «Diese Aussage ist unmöglich», die, insofern sie unmöglich ist, wahr ist, weil sie dem entspricht, was sie aussagt, und die dennoch, da sie, wie sie selbst sagt, unmöglich ist, auch falsch ist. Analog unterscheidet man die sich selbst aufhebenden Aussagen der Notwendigkeit, Kontingenz und Möglichkeit. Diese Probleme wurden in den Traktaten ‹De insolubilibus› diskutiert <sup class=\"fn\" data-fn=\"0-1\">1</sup> und haben großes Interesse bei den modernen mathematischen Logikern gefunden, die sie in Beziehung zu den semantischen und den syntaktischen Antinomien bringen.</p>\n<h3 id=\"notes\">Anmerkungen</h3><ol class=\"notes\">\n<li id=\"fn0-1\" value=\"1\">Vgl. z.B. ALBERT VON SACHSEN: Perutilis Logica (Venedig 1522) fol. 43ff.; PAULUS VENETUS: Logica Magna (Venedig 1499) fol. 192ff.</li>\n</ol>",
