 "html":"<p>Anagogé, Apagogé, Epagogé. Die syllogistischen Formeln zerfallen nach ARISTOTELES in vollkommene, als Axiome benutzte, und in unvollkommene, die durch ἀναγωγή (Rückführung) auf die vollkommenen, d.h. die der ersten Figur, als allgemeingültig zu erweisen sind <sup class=\"fn\" data-fn=\"0-1\">1</sup>. In sechs Fällen genügt es, auf Grund der Konversionssätze zu zeigen, daß durch äquivalente Umwandlung die betreffende unvollkommene Formel in eine vollkommene übergeht. Wo dies schwierig (Darapti, Felapton) oder unmöglich (Baroco, Bocardo) ist, wird die ἀπαγωγή zu Hilfe genommen, d.h. die zu den betreffenden Prämissen auf heuristischem Wege gefundene Konklusion wird behauptet. Dann wird angenommen, sie folge nicht, vielmehr seien sowohl die Prämissen als auch das kontradiktorische Gegenteil der behaupteten Konklusion wahr. Aus einer der Prämissen und dieser angenommenen Konklusion folgt aber auf Grund einer Formel der ersten Figur das kontradiktorische Gegenteil der anderen Prämisse, also: Diese Prämisse und ihr Gegenteil sind zusammen wahr, was unmöglich, absurd ist (reductio ad absurdum, indirekter Beweis, Satz vom Nicht-Widerspruch). Da aus der Annahme etwas Unmögliches folgt, ist sie falsch, ihr kontradiktorisches Gegenteil, die Behauptung, also wahr. Quod erat demonstrandum.</p>\n<p>Auch die ἐπαγωγή (Induktion) leitet Aristoteles aus dem Syllogismus her <sup class=\"fn\" data-fn=\"0-2\">2</sup>: Epagogé und ein Syllogismus aus ihr liegt vor, wenn mittels des terminus minor bewiesen wird, daß dem terminus medius der terminus maior als Prädikat zukommt. Es wird also ein fiktiver Schluß angenommen der Form: <i>a</i> von allen <i>b, b</i> von allen <i>c</i>, ergo <i>a</i> von allen <i>c.</i> In epagogische Form gebracht: <i>a</i> von allen <i>c, b</i> von allen c, ergo <i>a</i> von allen <i>b.</i> Syllogistisch zulässig ist der Schluß dann und nur dann, wenn ‹<i>b</i> von allen <i>c</i>› konvertibel ist, d.h. die Menge <i>B</i> keine Elemente enthält, die nicht zu <i>C</i> gehören und umgekehrt. Um sicher zu sein, daß dies der Fall ist, müssen mit <i>C</i> alle unter <i>B</i> fallenden Elemente erschöpft sein, unter Umständen also eine unendliche Aufzählung unternommen werden. Wohl weil er diese Aufzählung nicht für möglich hält, sagt Aristoteles, der Syllogismus mit Hilfe des terminus medius sei von Natur erkennbarer, der durch die Epagogé aber für uns einleuchtender <sup class=\"fn\" data-fn=\"0-3\">3</sup>.</p>\n<h3 id=\"h2\">Literaturhinweise</h3>\n<p class=\"lit\">Über die Entstehung des terminus technicus ‹Epagogé› und verwandter Wörter vgl. W. D. Ross: Aristotle's Prior and Posterior Analytics (Oxford 1949) 481–485.</p>\n<h3 id=\"notes\">Anmerkungen</h3><ol class=\"notes\">\n<li id=\"fn0-1\" value=\"1\">ARIST., Anal. pr. I, 1, 24 b 22.</li>\n<li id=\"fn0-2\" value=\"2\">a.a.O. II, 23, 68 b 15.</li>\n<li id=\"fn0-3\" value=\"3\">68 b 35.</li>\n</ol>",
